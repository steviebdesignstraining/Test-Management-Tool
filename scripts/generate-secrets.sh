#!/usr/bin/env bash
# generate-secrets.sh
# Dynamically generate secrets for the Test Management Tool and write them to .env.local
# Usage: ./generate-secrets.sh [--force]
#
# This script generates secure random values for all required secrets
# and writes them to .env.local. It never overwrites existing .env.local
# unless --force is passed.

set -euo pipefail

FORCE=false
if [[ "${1:-}" == "--force" ]]; then
  FORCE=true
fi

ENV_FILE=".env.local"

if [[ -f "$ENV_FILE" && "$FORCE" == false ]]; then
  echo "ERROR: $ENV_FILE already exists. Use --force to overwrite."
  exit 1
fi

# Generate a random hex string of given length
rand_hex() {
  openssl rand -hex "$1"
}

# Generate a random base64 string of given length
rand_b64() {
  openssl rand -base64 "$1" | tr -d '\n'
}

echo "Generating secrets for Test Management Tool..."

# Auth secret (NextAuth / session signing)
AUTH_SECRET=$(rand_b64 32)

# Neon Postgres connection (placeholder - user must supply real values)
DATABASE_URL="postgresql://neondb_owner:CHANGE_ME@ep-CHANGE_YOUR_HOST.aws.neon.tech/neondb?channel_binding=require&sslmode=require"
DATABASE_URL_UNPOOLED="postgresql://neondb_owner:CHANGE_ME@ep-CHANGE_YOUR_HOST.aws.neon.tech/neondb?channel_binding=require&sslmode=require"
NEON_BRANCH="production"

# Neon AI Gateway (placeholder - enable if you have a paid Neon plan)
NEON_AI_GATEWAY_URL="https://gateway.neon.tech/ai/v1"
NEON_AI_GATEWAY_API_KEY="CHANGE_ME"

# GitHub App / OAuth
GITHUB_APP_ID="CHANGE_ME"
GITHUB_APP_CLIENT_ID="CHANGE_ME"
GITHUB_APP_CLIENT_SECRET="CHANGE_ME"
GITHUB_APP_PRIVATE_KEY="-----BEGIN RSA PRIVATE KEY-----\nCHANGE_ME\n-----END RSA PRIVATE KEY-----"
GITHUB_APP_WEBHOOK_SECRET=$(rand_hex 32)

# Jira
JIRA_BASE_URL="https://your-instance.atlassian.net"
JIRA_EMAIL="CHANGE_ME"
JIRA_API_TOKEN="CHANGE_ME"

# Azure DevOps
AZURE_DEVOPS_ORGANIZATION_URL="https://dev.azure.com/your-organization"
AZURE_DEVOPS_PERSONAL_ACCESS_TOKEN="CHANGE_ME"

# Trello
TRELLO_API_KEY="CHANGE_ME"
TRELLO_API_TOKEN="CHANGE_ME"

# Application base URL
NEXT_PUBLIC_APP_URL="http://localhost:3001"

# Optional: S3 / object storage for attachments
AWS_ACCESS_KEY_ID="CHANGE_ME"
AWS_SECRET_ACCESS_KEY="CHANGE_ME"
AWS_S3_BUCKET="CHANGE_ME"
AWS_REGION="us-east-1"

# SMTP Email (required for email verification and password reset)
SMTP_HOST="smtp.example.com"
SMTP_PORT="587"
SMTP_USER="CHANGE_ME"
SMTP_PASS="CHANGE_ME"
SMTP_FROM="noreply@example.com"

# Encryption key for sensitive data (OAuth tokens)
ENCRYPTION_KEY=$(rand_hex 32)

cat > "$ENV_FILE" << EOF
# =============================================================================
# Test Management Tool - Environment Variables
# Generated by generate-secrets.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# =============================================================================

# --- Neon Postgres ---
DATABASE_URL="${DATABASE_URL}"
DATABASE_URL_UNPOOLED="${DATABASE_URL_UNPOOLED}"
NEON_BRANCH="${NEON_BRANCH}"

# --- Neon AI Gateway (paid plan required) ---
NEON_AI_GATEWAY_URL="${NEON_AI_GATEWAY_URL}"
NEON_AI_GATEWAY_API_KEY="${NEON_AI_GATEWAY_API_KEY}"

# --- Auth / Session ---
AUTH_SECRET="${AUTH_SECRET}"

# --- GitHub App ---
GITHUB_APP_ID="${GITHUB_APP_ID}"
GITHUB_APP_CLIENT_ID="${GITHUB_APP_CLIENT_ID}"
GITHUB_APP_CLIENT_SECRET="${GITHUB_APP_CLIENT_SECRET}"
GITHUB_APP_PRIVATE_KEY="${GITHUB_APP_PRIVATE_KEY}"
GITHUB_APP_WEBHOOK_SECRET="${GITHUB_APP_WEBHOOK_SECRET}"

# --- GitHub OAuth ---
GITHUB_CLIENT_ID="${GITHUB_APP_CLIENT_ID}"
GITHUB_CLIENT_SECRET="${GITHUB_APP_CLIENT_SECRET}"
GITHUB_CALLBACK_URL="http://localhost:3001/api/v1/auth/github/callback"

# --- Jira ---
JIRA_BASE_URL="${JIRA_BASE_URL}"
JIRA_EMAIL="${JIRA_EMAIL}"
JIRA_API_TOKEN="${JIRA_API_TOKEN}"

# --- Azure DevOps ---
AZURE_DEVOPS_ORGANIZATION_URL="${AZURE_DEVOPS_ORGANIZATION_URL}"
AZURE_DEVOPS_PERSONAL_ACCESS_TOKEN="${AZURE_DEVOPS_PERSONAL_ACCESS_TOKEN}"

# --- Trello ---
TRELLO_API_KEY="${TRELLO_API_KEY}"
TRELLO_API_TOKEN="${TRELLO_API_TOKEN}"

# --- Application ---
NEXT_PUBLIC_APP_URL="${NEXT_PUBLIC_APP_URL}"

# --- Object Storage (attachments) ---
AWS_ACCESS_KEY_ID="${AWS_ACCESS_KEY_ID}"
AWS_SECRET_ACCESS_KEY="${AWS_SECRET_ACCESS_KEY}"
AWS_S3_BUCKET="${AWS_S3_BUCKET}"
AWS_REGION="${AWS_REGION}"

# --- SMTP Email ---
SMTP_HOST="${SMTP_HOST}"
SMTP_PORT="${SMTP_PORT}"
SMTP_USER="${SMTP_USER}"
SMTP_PASS="${SMTP_PASS}"
SMTP_FROM="${SMTP_FROM}"

# --- Encryption key for sensitive data ---
ENCRYPTION_KEY="${ENCRYPTION_KEY}"
EOF

echo "Secrets written to $ENV_FILE"
echo ""
echo "IMPORTANT NEXT STEPS:"
echo "1. Replace all CHANGE_ME values with real credentials."
echo "2. Add the following secrets to your GitHub repository or CI/CD platform:"
echo "   - DATABASE_URL"
echo "   - DATABASE_URL_UNPOOLED"
echo "   - AUTH_SECRET"
echo "   - GITHUB_APP_PRIVATE_KEY"
echo "   - GITHUB_APP_CLIENT_SECRET"
echo "   - GITHUB_APP_WEBHOOK_SECRET"
echo "   - JIRA_API_TOKEN"
echo "   - AZURE_DEVOPS_PERSONAL_ACCESS_TOKEN"
echo "   - AWS_SECRET_ACCESS_KEY"
echo "   - ENCRYPTION_KEY"
echo "3. Run 'npm run db:migrate' (or equivalent) to apply migrations."
echo "4. Run 'npm run dev' to start the application."
echo ""
echo "WARNING: Never commit $ENV_FILE to version control."